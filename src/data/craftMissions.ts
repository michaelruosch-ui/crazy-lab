import type { Mission } from '../domain'

type CraftMissionInput = Omit<
  Mission,
  'primaryCategory' | 'secondaryCategories' | 'location' | 'drinkProfile'
> & {
  secondaryCategories?: Mission['secondaryCategories']
  location?: Mission['location']
}

function craftMission(input: CraftMissionInput): Mission {
  return {
    ...input,
    primaryCategory: 'basteln',
    secondaryCategories: input.secondaryCategories ?? [],
    location: input.location ?? 'zimmer',
  }
}

